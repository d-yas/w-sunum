import { parseNumber, parseDate, parseDelimited } from "../src/lib/parse.ts";
import { formatNumber, formatTick } from "../src/lib/format.ts";
const eq = (a, b, m) => { const ok = JSON.stringify(a) === JSON.stringify(b); console.log(ok ? "ok  " : "FAIL", m, ok ? "" : `→ got ${JSON.stringify(a)}`); };
eq(parseNumber("1.250,5"), 1250.5, "tr decimal comma");
eq(parseNumber("1,250.5"), 1250.5, "en decimal dot");
eq(parseNumber("1.250"), 1250, "tr thousands dot");
eq(parseNumber("1,250", "en-US"), 1250, "en thousands comma");
eq(parseNumber("12,5"), 12.5, "single comma decimal");
eq(parseNumber("%12"), 12, "percent prefix");
eq(parseNumber("₺ 1.500"), 1500, "currency + space");
eq(parseNumber("−3"), -3, "unicode minus");
eq(parseNumber(""), null, "empty");
eq(parseNumber("abc"), null, "text");
const d = (x) => { const r = parseDate(x); return r ? `${r.getFullYear()}-${r.getMonth()+1}-${r.getDate()}` : null; };
eq(d("2025-03-14"), "2025-3-14", "iso");
eq(d("14.03.2025"), "2025-3-14", "tr dotted");
eq(d("14/03/2025"), "2025-3-14", "slashed");
eq(d("2025-03"), "2025-3-1", "year-month");
eq(d("Mar 2025"), "2025-3-1", "month name");
eq(d("Oca 2025"), "2025-1-1", "tr month name");
eq(d("Ç1 2025"), "2025-1-1", "quarter tr");
eq(d("Q3 2025"), "2025-7-1", "quarter en");
eq(d("2024"), "2024-1-1", "bare year");
eq(d("Ürün A"), null, "category is not a date");
eq(parseDelimited("a\tb\tc\n1\t2\t3"), [["a","b","c"],["1","2","3"]], "tsv");
eq(parseDelimited("a;b\n1;\"x;y\""), [["a","b"],["1","x;y"]], "semicolon with quotes");
eq(parseDelimited("a,b\r\n1,2\r\n"), [["a","b"],["1","2"]], "csv crlf");
const f = { locale: "tr-TR", decimals: 1, prefix: "", suffix: " ₺", compact: false };
eq(formatNumber(1250.55, f), "1.250,6 ₺", "format tr");
eq(formatTick(0.25, { ...f, decimals: 0, suffix: "" }, 0.25), "0,25", "tick fractional step");
eq(formatNumber(1250000, { ...f, compact: true, decimals: 1, suffix: "" }).replace(/ /g, " "), "1,3 Mn", "compact tr");
